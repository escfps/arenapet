export type Element = "fire" | "water" | "grass" | "electric" | "shadow" | "earth" | "psychic" | "fairy";
export type Role = "tank" | "dps" | "assassin" | "mage" | "healer";
export type Rarity = "common" | "rare" | "super_rare" | "epic" | "legendary" | "mythic";

export type Species = {
  id: string;
  name: string;
  element: Element;
  secondaryElement?: Element; // hybrids have two
  role: Role;
  rarity: Rarity;
  emoji: string;
  image: string;
  shinyImage?: string; // ✨ arte alternativa shiny
  description: string;
  base: { hp: number; atk: number; def: number; spd: number; int: number };
  skill?: Skill; // unique skill per species (overrides ROLE_SKILLS)
  /**
   * Pets ocultos: NÃO aparecem em baús, baú de boas-vindas, nem na Coleção
   * pública (a menos que o jogador já tenha um). Servem para testes em conta
   * admin antes do lançamento oficial. Para "soltar" o pet pra todos, basta
   * remover esta flag (ou setar para false) e publicar.
   */
  hidden?: boolean;
  /** Pet legado desativado do jogo (oculto em tudo, mas mantido para pets já existentes) */
  retired?: boolean;
};

