export function rollShiny(rand: () => number = Math.random): boolean {
  return rand() < SHINY_CHANCE;
}
/** Roll de Shiny escalado por raridade: Míticos são ~20x mais raridos que Comuns. */
export function rollShinyForRarity(rarity: Rarity, rand: () => number = Math.random): boolean {
  return rand() < SHINY_CHANCE * (SHINY_RARITY_MULT[rarity] ?? 1);
}

export type ChestReward = {
  coins: number;
  gems: number;
  rations: number;
  petSpecies?: string; // id da espécie sorteada (se caiu pet)
  petShiny?: boolean; // ✨ ultra raro (1% de chance)
};


export function rollChest(tier: ChestTier, forceRarity?: Rarity): ChestReward {
  const c = CHESTS[tier];
  const rng = (range: [number, number]) =>
    Math.floor(Math.random() * (range[1] - range[0] + 1)) + range[0];

  const coins = rng(c.coins);
  const rations = rng(c.rations);
  const gems = Math.random() < c.gemChance ? rng(c.gems) : 0;

  let petSpecies: string | undefined;
  const shouldDropPet = forceRarity ? true : Math.random() < c.petChance;
  if (shouldDropPet) {
    let chosenRarity: Rarity = "common";
    if (forceRarity) {
      chosenRarity = forceRarity;
    } else {
      const totalW = Object.values(c.petRarityWeights).reduce((a, b) => a + (b ?? 0), 0);
      let r = Math.random() * totalW;
      for (const [rarity, weight] of Object.entries(c.petRarityWeights)) {
        r -= weight ?? 0;
        if (r <= 0) { chosenRarity = rarity as Rarity; break; }
      }
    }
    const activeSpecies = Object.values(SPECIES).filter((s) => !s.hidden && !s.retired);
    // Ordem de fallback: se não existir pet ativo na raridade sorteada, desce/sobe para a mais próxima
    const RARITY_ORDER: Rarity[] = ["common", "rare", "super_rare", "epic", "legendary", "mythic"];
    let pool = activeSpecies.filter((s) => s.rarity === chosenRarity);
    if (pool.length === 0) {
      const idx = RARITY_ORDER.indexOf(chosenRarity);
      for (let d = 1; d < RARITY_ORDER.length && pool.length === 0; d++) {
        for (const alt of [RARITY_ORDER[idx - d], RARITY_ORDER[idx + d]]) {
          if (!alt) continue;
          const p = activeSpecies.filter((s) => s.rarity === alt);
          if (p.length > 0) { pool = p; break; }
        }
      }
    }
    if (pool.length > 0) {
      petSpecies = pool[Math.floor(Math.random() * pool.length)].id;
    }

  }

  // ✨ Shiny só pode sair no Baú Lendário
  const petShiny = petSpecies && (tier === "legendary" || tier === "mythic") ? rollShiny() : false;

  return { coins, gems, rations, petSpecies, petShiny };

}

